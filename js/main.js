document.addEventListener('DOMContentLoaded', () => {
  initLanguage();
  initNavbar();
  initScrollReveal();
});

function initLanguage() {
  const buttons = document.querySelectorAll('[data-language-option], [data-language]');
  const initialLanguage = localStorage.getItem('sunbridge-language') || 'en';

  function setLanguage(language) {
    const dictionary = translations[language] || translations.en;
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    document.body.dataset.language = language;
    localStorage.setItem('sunbridge-language', language);

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const value = dictionary[element.dataset.i18n];
      if (value !== undefined) element.textContent = value;
    });

    const titleKey = document.body.dataset.titleKey;
    const descriptionKey = document.body.dataset.descriptionKey;
    if (titleKey && dictionary[titleKey]) document.title = dictionary[titleKey];
    if (descriptionKey && dictionary[descriptionKey]) {
      document.querySelector('meta[name="description"]')?.setAttribute('content', dictionary[descriptionKey]);
    }

    buttons.forEach((button) => {
      const buttonLanguage = button.dataset.languageOption || button.dataset.language;
      const active = buttonLanguage === language;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
  }

  buttons.forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.languageOption || button.dataset.language));
  });
  setLanguage(initialLanguage);
}

function initNavbar() {
  const header = document.querySelector('.site-header');
  const toggle = document.querySelector('.menu-toggle, .mobile-toggle');
  const mobileNav = document.querySelector('.mobile-nav');

  window.addEventListener('scroll', () => {
    header?.classList.toggle('scrolled', window.scrollY > 24);
  }, { passive: true });

  if (!toggle || !mobileNav) return;
  const setOpen = (open) => {
    toggle.classList.toggle('active', open);
    toggle.setAttribute('aria-expanded', String(open));
    mobileNav.classList.toggle('open', open);
    document.body.classList.toggle('menu-open', open);
  };
  toggle.addEventListener('click', () => setOpen(!mobileNav.classList.contains('open')));
  mobileNav.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => setOpen(false)));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') setOpen(false);
  });
}

function initScrollReveal() {
  const elements = document.querySelectorAll('.reveal');
  if (!('IntersectionObserver' in window)) {
    elements.forEach((element) => element.classList.add('reveal-active'));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('reveal-active');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -40px' });
  elements.forEach((element) => observer.observe(element));
}
